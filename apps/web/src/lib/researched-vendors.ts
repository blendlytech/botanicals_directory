export function getResearchedVendor(slug: string) {
  return researchedVendors.find(v => v.slug === slug);
}
// Once ownership is reviewed, owner-managed database content takes precedence.
export function researchForListing(vendor: { slug: string; ownership_verified_at?: string | null }) {
  return vendor.ownership_verified_at ? undefined : getResearchedVendor(vendor.slug);
}

export function withResearch<T extends { slug: string; ownership_verified_at?: string | null }>(vendor: T) {
  const p = researchForListing(vendor);
  if (!p) return vendor;
  return { ...vendor, name: p.name, specialty: p.specialty,
    location_city: p.city, location_state: p.state, location_country: "US",
    logo_url: null, hero_url: null, is_verified: false, is_elite: false };
}
